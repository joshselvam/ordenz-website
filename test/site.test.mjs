  assert.doesNotMatch(c,/\.hero-art\.has-video:after\{display:none\}/);
  assert.doesNotMatch(c,/height:58%|height:42%|width:72%/);
  assert.doesNotMatch(h,/dual display|two monitors|PC \+/i);
